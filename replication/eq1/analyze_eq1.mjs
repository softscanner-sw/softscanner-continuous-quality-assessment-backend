#!/usr/bin/env node
// EQ1 (human-process effect): recompute the reported assessment-time statistics from the retained
// participant-level times. Precision and recall are retained historical values (one value per
// participant and condition) whose derivation was not retained; they are reported, not recomputed.
//
// Usage:  node replication/eq1/analyze_eq1.mjs [--check]
//   --check   exit with code 1 if any recomputed value differs from the value reported in the
//             dissertation at the reported precision (see replication/results/manuscript_reported_values.json).
// Outputs (overwritten): replication/results/eq1_report.md, replication/results/eq1_time_statistics.csv
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const RESULTS = join(HERE, '..', 'results');
const CHECK = process.argv.includes('--check');

function readCsv(file) {
  const [head, ...lines] = readFileSync(join(HERE, 'data', file), 'utf8').split(/\r?\n/).filter((l) => l);
  const cols = head.split(',');
  return lines.map((l) => Object.fromEntries(l.split(',').map((v, i) => [cols[i], i === 0 ? v : Number(v)])));
}

const times = readCsv('eq1_assessment_times.csv');
const pr = readCsv('eq1_reported_precision_recall.csv');
if (times.length !== 6) throw new Error(`expected 6 participants, found ${times.length}`);

const mean = (xs) => xs.reduce((a, b) => a + b, 0) / xs.length;
const median = (xs) => { const s = [...xs].sort((a, b) => a - b); const n = s.length; return n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2; };
const popSd = (xs) => { const m = mean(xs); return Math.sqrt(mean(xs.map((x) => (x - m) ** 2))); };
const cv = (xs) => (popSd(xs) / mean(xs)) * 100; // population SD / mean (as stated in Section 4.4.1)

const base = times.map((t) => t.baseline_time_s);
const ss = times.map((t) => t.softscanner_time_s);
const reductions = times.map((t) => (1 - t.softscanner_time_s / t.baseline_time_s) * 100);

const stats = {
  baseline_min_s: Math.min(...base), baseline_max_s: Math.max(...base), baseline_median_s: median(base),
  softscanner_min_s: Math.min(...ss), softscanner_max_s: Math.max(...ss), softscanner_median_s: median(ss),
  median_participant_reduction_pct: median(reductions),
  cv_baseline_pct: cv(base), cv_softscanner_pct: cv(ss),
};

writeFileSync(join(RESULTS, 'eq1_time_statistics.csv'),
  ['statistic,value', ...Object.entries(stats).map(([k, v]) => `${k},${Number.isInteger(v) ? v : v.toFixed(6)}`)].join('\n') + '\n');

const reported = JSON.parse(readFileSync(join(RESULTS, 'manuscript_reported_values.json'), 'utf8')).eq1;
const cmp = Object.entries(reported.recomputable).map(([k, r]) => {
  const v = stats[k];
  return { item: k, recomputed: v, reported: r.value, dec: r.decimals, match: Number(v.toFixed(r.decimals)) === r.value };
});

const md = [];
md.push('# EQ1 recomputation report', '');
md.push('Generated by `node replication/eq1/analyze_eq1.mjs`. Inputs: `replication/eq1/data/` (six participants, one recorded assessment time per participant and condition).', '');
md.push('## Per-participant assessment times', '');
md.push('| Participant | Semi-automatic baseline (s) | SoftScanner-NFA (s) | Reduction % |', '|---|---:|---:|---:|');
times.forEach((t, i) => md.push(`| ${t.participant} | ${t.baseline_time_s} | ${t.softscanner_time_s} | ${reductions[i].toFixed(2)} |`));
md.push('', '## Recomputed statistics compared with the dissertation (Section 4.4.1)', '');
md.push('| Statistic | Recomputed | Rounded | Reported | Match |', '|---|---:|---:|---:|---|');
for (const c of cmp) md.push(`| ${c.item} | ${Number.isInteger(c.recomputed) ? c.recomputed : c.recomputed.toFixed(4)} | ${c.recomputed.toFixed(c.dec)} | ${c.reported} | ${c.match ? 'yes' : '**NO**'} |`);
md.push('', `Result: ${cmp.filter((c) => c.match).length}/${cmp.length} reported time statistics reproduced at the reported precision.`, '');
md.push('Notes: the median of six values is the mean of the two middle values; the coefficient of variation uses the population standard deviation, as stated in the dissertation.', '');
md.push('## Precision and recall (retained historical values, not recomputed)', '');
md.push('| Participant | Precision baseline % | Precision SoftScanner % | Recall baseline % | Recall SoftScanner % |', '|---|---:|---:|---:|---:|');
pr.forEach((p) => md.push(`| ${p.participant} | ${p.precision_baseline_pct} | ${p.precision_softscanner_pct} | ${p.recall_baseline_pct} | ${p.recall_softscanner_pct} |`));
md.push('', 'These values are transcribed from the retained study results. The reference observations and collected observations from which they were derived are not part of the retained evidence, so they cannot be recomputed from this package.');
writeFileSync(join(RESULTS, 'eq1_report.md'), md.join('\n') + '\n');

console.log(md.join('\n'));
if (CHECK && cmp.some((c) => !c.match)) { console.error('EQ1 check FAILED'); process.exit(1); }
